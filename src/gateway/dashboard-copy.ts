export type DashboardCopyKey = (typeof dashboardCopyKeys)[number];
export type DashboardCopy = Readonly<Record<DashboardCopyKey, string>>;

export function getDashboardCopy(locale: DashboardLocale): DashboardCopy {
  return locale === "zh-CN" ? dashboardCopyZhCn : dashboardCopyEn;
}

export function formatDashboardCopy(
  copy: DashboardCopy,
  key: DashboardCopyKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return copy[key].replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
